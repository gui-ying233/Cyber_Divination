from 易卦 import 卦名

八卦爻: dict[str, int] = {
    "乾": 0b111, "坎": 0b010, "艮": 0b100, "震": 0b001,
    "巽": 0b110, "离": 0b101, "坤": 0b000, "兑": 0b011,
}
爻八卦: dict[int, str] = {爻: 卦 for 卦, 爻 in 八卦爻.items()}
八宫五行: dict[str, str] = {
    "乾": "金", "坎": "水", "艮": "土", "震": "木",
    "巽": "木", "离": "火", "坤": "土", "兑": "金",
}
变爻位: tuple[int, ...] = (0, 1, 3, 7, 15, 31, 23, 16)
世爻位: tuple[int, ...] = (6, 1, 2, 3, 4, 5, 4, 3)
卦表: dict[int, tuple[str, int]] = {}
for 宫 in 八卦爻:
    本宫卦 = 八卦爻[宫] * 9
    for 序, 变位 in enumerate(变爻位):
        卦表[本宫卦 ^ 变位] = (宫, 世爻位[序])

纳甲: dict[str, tuple[str, ...]] = {
    "乾": ("甲子", "甲寅", "甲辰", "壬午", "壬申", "壬戌"),
    "坎": ("戊寅", "戊辰", "戊午", "戊申", "戊戌", "戊子"),
    "艮": ("丙辰", "丙午", "丙申", "丙戌", "丙子", "丙寅"),
    "震": ("庚子", "庚寅", "庚辰", "庚午", "庚申", "庚戌"),
    "巽": ("辛丑", "辛亥", "辛酉", "辛未", "辛巳", "辛卯"),
    "离": ("己卯", "己丑", "己亥", "己酉", "己未", "己巳"),
    "坤": ("乙未", "乙巳", "乙卯", "癸丑", "癸亥", "癸酉"),
    "兑": ("丁巳", "丁卯", "丁丑", "丁亥", "丁酉", "丁未"),
}
地支五行: dict[str, str] = {
    "子": "水", "丑": "土", "寅": "木", "卯": "木", "辰": "土", "巳": "火",
    "午": "火", "未": "土", "申": "金", "酉": "金", "戌": "土", "亥": "水",
}
相生: dict[str, str] = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}
相克: dict[str, str] = {"木": "土", "土": "水", "水": "火", "火": "金", "金": "木"}
六神: tuple[str, ...] = ("青龙", "朱雀", "勾陈", "螣蛇", "白虎", "玄武")
日干起神: dict[str, int] = {
    "甲": 0, "乙": 0, "丙": 1, "丁": 1, "戊": 2,
    "己": 3, "庚": 4, "辛": 4, "壬": 5, "癸": 5,
}


def 装甲(卦: int) -> tuple[str, ...]:
    return 纳甲[爻八卦[卦 & 0b111]][:3] + 纳甲[爻八卦[卦 >> 3]][3:]


def 定六亲(宫行: str, 爻支: str) -> str:
    爻行 = 地支五行[爻支]
    if 爻行 == 宫行:
        return "兄弟"
    if 相生[爻行] == 宫行:
        return "父母"
    if 相生[宫行] == 爻行:
        return "子孙"
    if 相克[爻行] == 宫行:
        return "官鬼"
    return "妻财"


取数 = input("从初爻到上爻输入六个爻数（6老阴、7少阳、8少阴、9老阳），用空格分隔：")
try:
    六爻 = tuple(map(int, 取数.split()))
except ValueError as 错误:
    raise ValueError("请输入六个6、7、8或9") from 错误
if len(六爻) != 6 or any(爻 not in (6, 7, 8, 9) for 爻 in 六爻):
    raise ValueError("请输入六个6、7、8或9")

日干 = input("占日天干（甲至癸，直接回车则不排六神）：").strip()
if 日干 and 日干 not in 日干起神:
    raise ValueError("日干应为甲、乙、丙、丁、戊、己、庚、辛、壬或癸")
if 日干:
    六神起例 = input("六神起例：1《卜筮正宗》《增删卜易》，2杨慎《升庵先生文集》（输入1或2）：").strip()
    if 六神起例 not in ("1", "2"):
        raise ValueError("六神起例请输入1或2")
    if 六神起例 == "2":
        日干起神["己"] = 2
        日干起神["壬"] = 3

主卦 = sum((爻 % 2) << 序 for 序, 爻 in enumerate(六爻))
变卦 = 主卦 ^ sum(1 << 序 for 序, 爻 in enumerate(六爻) if 爻 in (6, 9))
主宫, 世 = 卦表[主卦]
变宫, _ = 卦表[变卦]
应 = (世 + 2) % 6 + 1
主甲 = 装甲(主卦)
变甲 = 装甲(变卦)
宫行 = 八宫五行[主宫]

print(f"主卦：{卦名(六爻)}（{主宫}宫，属{宫行}，世{世}应{应}）")
print(f"变卦：{卦名(tuple(变卦 >> 序 & 1 for 序 in range(6)))}（{变宫}宫）"
      + ("" if 变卦 != 主卦 else "，无动爻"))
for 序 in range(5, -1, -1):
    爻 = 六爻[序]
    纳支 = 主甲[序][1]
    神 = f"{六神[(日干起神[日干] + 序) % 6]} " if 日干 else ""
    世应 = "世" if 序 + 1 == 世 else "应" if 序 + 1 == 应 else "  "
    动 = "○" if 爻 == 9 else "×" if 爻 == 6 else " "
    变 = f" → {定六亲(宫行, 变甲[序][1])} {变甲[序]}" if 爻 in (6, 9) else ""
    print(f"{('初', '二', '三', '四', '五', '上')[序]}爻 {神}{定六亲(宫行, 纳支)} {主甲[序]} "
          f"{'⚊' if 爻 % 2 else '⚋'} {动} {世应}{变}")
