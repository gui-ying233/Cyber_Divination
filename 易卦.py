def 卦名(爻: tuple[int, ...]) -> str:
    if len(爻) != 6 or any(n not in (0, 1, 6, 7, 8, 9) for n in 爻):
        raise ValueError("须输入从初爻到上爻的六个阴阳或爻数")
    位 = tuple(n % 2 for n in 爻)
    下卦 = (位[0] << 2) | (位[1] << 1) | 位[2]
    上卦 = (位[3] << 2) | (位[4] << 1) | 位[5]
    return 六十四卦[下卦 << 3 | 上卦]
