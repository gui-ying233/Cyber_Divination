def 克(甲: str, 乙: str) -> bool:
    return 相克[甲] == 乙


def 六亲(日行: str, 神支: str) -> str:
    神行 = 支行[神支]
    if 神行 == 日行:
        return "兄弟"
    if 相生[神行] == 日行:
        return "父母"
    if 相生[日行] == 神行:
        return "子孙"
    if 克(神行, 日行):
        return "官鬼"
    return "妻财"


def 冲(支: str) -> str:
    return 地支[(地支.index(支) + 6) % 12]


def 涉害数(课: tuple[str, str, str], 下贼: bool) -> int:
    上, 地位 = 课[1], 课[2]
    数 = 0
    位 = (地支.index(地位) + 1) % 12
    while 地支[位] != 上:
        支 = 地支[位]
        众 = [支行[支]] + [干行[干] for 干 in 天干 if 寄宫[干] == 支]
        数 += sum(克(行, 支行[上]) if 下贼 else 克(支行[上], 行) for 行 in 众)
        位 = (位 + 1) % 12
    return 数


def 取克用(候选: list[int], 课: list[tuple[str, str, str]], 日干: str, 下贼: bool) -> tuple[str, str, int]:
    若干: list[int] = []
    for 序 in 候选:
        if (课[序][1], 课[序][2]) not in [(课[旧][1], 课[旧][2]) for 旧 in 若干]:
            若干.append(序)
    if len({课[序][1] for 序 in 若干}) == 1:
        return 课[若干[0]][1], "重审" if 下贼 else "元首", 若干[0]
    比 = [序 for 序 in 若干 if 地支.index(课[序][1]) % 2 == 天干.index(日干) % 2]
    if len(比) == 1:
        return 课[比[0]][1], "比用", 比[0]
    若干 = 比 or 若干
    涉法 = input("涉害取法：1《六壬大全》计克，2《六壬指南》先地盘孟仲季，3《御定六壬直指》计克后按上神孟仲季：").strip()
    if 涉法 not in ("1", "2", "3"):
        raise ValueError("涉害取法请输入1、2或3")
    if 涉法 in ("1", "3"):
        深 = max(涉害数(课[序], 下贼) for 序 in 若干)
        若干 = [序 for 序 in 若干 if 涉害数(课[序], 下贼) == 深]
    位次 = ("寅申巳亥", "子午卯酉", "辰戌丑未")
    地神 = 1 if 涉法 == "3" else 2
    层 = min(next(i for i, 组 in enumerate(位次) if 课[序][地神] in 组) for 序 in 若干)
    若干 = [序 for 序 in 若干 if 课[序][地神] in 位次[层]]
    若干.sort(key=lambda 序: (序 >= 2 if 天干.index(日干) % 2 == 0 else 序 < 2, 序))
    return 课[若干[0]][1], "涉害", 若干[0]


