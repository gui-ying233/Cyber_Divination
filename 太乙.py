def 投算(目: int, 太乙宫: int) -> int:
    止宫 = next(位 for 位, 数 in 正宫数.items() if 数 == 太乙宫)
    算 = 正宫数.get(目, 1)
    if 目 != 止宫:
        位 = (目 + 1) % 16
        while 位 != 止宫:
            算 += 正宫数.get(位, 0)
            位 = (位 + 1) % 16
    return 算


def 将宫(算: int) -> tuple[int, int]:
    大将 = 算 % 10 or 算 // 10
    参数 = 大将 * 3
    参将 = 参数 % 10 or 参数 // 10
    return 大将, 参将


